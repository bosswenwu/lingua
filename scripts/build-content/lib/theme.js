/* 单个释义段 → 命中的主题（长关键词优先，再单字兜底；段命中反例表的主题跳过；
   单字关键词要求段长 ≤3 且以该字开头/结尾，拦截段中误配如「维生素」中「生」） */
function matchSeg(seg) {
  const banned = (t) => {
    const b = BAN.get(seg);
    if (b && b.has(t.slug)) return true;
    for (const [s, slugs] of BAN) if (seg.indexOf(s) >= 0 && slugs.has(t.slug)) return true;
    return false;
  };
  for (const t of THEMES) {
    if (!t.kw.length || banned(t)) continue;
    for (const kw of t.kw) if (kw.length >= 2 && seg.indexOf(kw) >= 0) return t;
  }
  for (const t of THEMES) {
    if (!t.kw.length || banned(t)) continue;
    for (const kw of t.kw) {
      if (kw.length === 1 && seg.length <= 3 && (seg[0] === kw || seg[seg.length - 1] === kw)) return t;
    }
  }
  return null;
}

/* 词条归类：释义按分号拆段，取首个命中段；全无命中 → 基础词汇 */
function wordTheme(m) {
  for (const seg of String(m || "").split(/[；;]/)) {
    const t = matchSeg(seg);
    if (t) return t;
  }
  return BASE;
}

